import { readFileSync, writeFileSync } from "node:fs";
import solc from "solc";

const source = readFileSync(new URL("../contracts/StockClub.sol", import.meta.url), "utf8");
const input = {
  language: "Solidity",
  sources: { "StockClub.sol": { content: source } },
  settings: {
    optimizer: { enabled: true, runs: 200 },
    outputSelection: { "*": { "*": ["abi", "evm.bytecode.object", "evm.deployedBytecode.object"] } },
  },
};
const output = JSON.parse(solc.compile(JSON.stringify(input)));
const errors = (output.errors ?? []).filter((item) => item.severity === "error");
if (errors.length) {
  console.error(errors.map((item) => item.formattedMessage).join("\n"));
  process.exit(1);
}
const contract = output.contracts["StockClub.sol"].StockClub;
const file = `/* Generated by scripts/compile-club.mjs. Do not edit. */
export const CLUB_ABI = ${JSON.stringify(contract.abi, null, 2)} as const;

export const CLUB_BYTECODE = "0x${contract.evm.bytecode.object}" as const;

export const CLUB_DEPLOYED_BYTECODE = "0x${contract.evm.deployedBytecode.object}" as const;
`;
writeFileSync(new URL("../src/lib/stockclub/club-bytecode.ts", import.meta.url), file);
console.log("bytecode", contract.evm.bytecode.object.length / 2, "bytes");
